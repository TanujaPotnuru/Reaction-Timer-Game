`timescale 1ns / 1ps

module top_level_tb;

    //----------------------------------------------------------
    // Inputs
    //----------------------------------------------------------

    reg CLOCK_50;
    reg [1:0] KEY;
    reg [0:0] SW;

    //----------------------------------------------------------
    // Outputs
    //----------------------------------------------------------

    wire [9:0] LEDR;
    wire GPIO_0;
    wire GPIO_1;

    wire [7:0] HEX0;
    wire [7:0] HEX1;
    wire [7:0] HEX2;
    wire [7:0] HEX3;

    //----------------------------------------------------------
    // DUT
    //----------------------------------------------------------

    top_level DUT
    (
        .CLOCK_50(CLOCK_50),
        .KEY(KEY),
        .SW(SW),

        .LEDR(LEDR),
        .GPIO_0(GPIO_0),
        .GPIO_1(GPIO_1),

        .HEX0(HEX0),
        .HEX1(HEX1),
        .HEX2(HEX2),
        .HEX3(HEX3)
    );

    //----------------------------------------------------------
    // 50 MHz Clock
    //----------------------------------------------------------

    initial
    begin
        CLOCK_50 = 0;
        forever #1 CLOCK_50 = ~CLOCK_50;
    end

    //----------------------------------------------------------
    // Manual Stimulus
    //----------------------------------------------------------

    initial
    begin

        //-----------------------------
        // Initial values
        //-----------------------------

        KEY = 2'b11;     // buttons released
        SW  = 1'b0;      // show reaction time

        //--------------------------------------------------
        // Wait a little
        //--------------------------------------------------

        #50;

        //--------------------------------------------------
        // START BUTTON
        //--------------------------------------------------

        // KEY0 is active LOW

        KEY[0] = 0;

        #40;

        KEY[0] = 1;

        //--------------------------------------------------
        // Wait for complete game
        //--------------------------------------------------

        #1500;

        //--------------------------------------------------
        // Press REACT button
        //--------------------------------------------------

        KEY[1] = 0;

        #40;

        KEY[1] = 1;

        //--------------------------------------------------
        // Observe result
        //--------------------------------------------------

        #300;

        //--------------------------------------------------
        // Display BEST TIME
        //--------------------------------------------------

        SW = 1;

        #300;

        //--------------------------------------------------
        // Second Game
        //--------------------------------------------------

        SW = 0;

        KEY[0] = 0;

        #40;

        KEY[0] = 1;

        //--------------------------------------------------
        // Wait
        //--------------------------------------------------

        #1500;

        //--------------------------------------------------
        // React Faster
        //--------------------------------------------------

        KEY[1] = 0;

        #20;

        KEY[1] = 1;

        //--------------------------------------------------
        // Show Best Time
        //--------------------------------------------------

        #300;

        SW = 1;

        #500;

        $finish;

    end

    //----------------------------------------------------------
    // Monitor
    //----------------------------------------------------------

    initial
    begin

        $monitor(

        "T=%0t  KEY=%b  LED=%b  GO=%b  WAIT=%b  HEX3=%h HEX2=%h HEX1=%h HEX0=%h",

        $time,

        KEY,

        LEDR,

        GPIO_0,

        GPIO_1,

        HEX3,
        HEX2,
        HEX1,
        HEX0

        );

    end

endmodule